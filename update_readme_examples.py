"""Regenerate the Examples grid in README.md from the tools manifest.

Lists every tool with `has_python_example` and a matching notebook in
examples/, showing its poster from the website when one exists. The
generated block lives between the EXAMPLES markers in README.md.
"""

import html
import json
import pathlib
import sys

BASE_DIR = pathlib.Path(__file__).resolve().parent
README = BASE_DIR / "README.md"
EXAMPLES_DIR = BASE_DIR / "examples"
MONET_DIR = BASE_DIR / "../../js/monet"
TOOLS_MANIFEST = MONET_DIR / "src/app/tools/tools_manifest.json"
PUBLIC_TOOLS_DIR = MONET_DIR / "public/tools"

SITE_URL = "https://www.brushcue.com"
START_MARKER = "<!-- EXAMPLES:START (generated by update_readme_examples.py) -->"
END_MARKER = "<!-- EXAMPLES:END -->"
COLUMNS = 4


def build_section() -> str:
    tools = json.loads(TOOLS_MANIFEST.read_text())
    examples = sorted(
        (
            tool
            for slug, tool in tools.items()
            if tool.get("has_python_example", True)
            and (EXAMPLES_DIR / f"{slug.replace('-', '_')}.ipynb").exists()
        ),
        key=lambda tool: tool["name"].lower(),
    )

    with_poster = [t for t in examples if (PUBLIC_TOOLS_DIR / t["slug"] / "poster.jpeg").exists()]
    without_poster = [t for t in examples if t not in with_poster]

    lines = ["<table>"]
    for row_start in range(0, len(with_poster), COLUMNS):
        lines.append("<tr>")
        for tool in with_poster[row_start : row_start + COLUMNS]:
            slug = tool["slug"]
            name = html.escape(tool["name"])
            lines.append(
                f'<td align="center" width="{100 // COLUMNS}%">'
                f'<a href="{SITE_URL}/docs/py/examples/{slug}">'
                f'<img src="{SITE_URL}/tools/{slug}/poster.jpeg" width="180" alt="{name}">'
                f"<br>{name}</a></td>"
            )
        lines.append("</tr>")
    lines.append("</table>")

    if without_poster:
        lines += ["", "Additional examples without previews:", ""]
        lines += [
            f"- [{tool['name']}]({SITE_URL}/docs/py/examples/{tool['slug']})"
            for tool in without_poster
        ]

    print(f"README examples: {len(with_poster)} with posters, {len(without_poster)} without")
    return "\n".join(lines)


def main() -> None:
    readme = README.read_text()
    start = readme.find(START_MARKER)
    end = readme.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        sys.exit(f"README examples markers not found in {README}")
    updated = (
        readme[: start + len(START_MARKER)]
        + "\n"
        + build_section()
        + "\n"
        + readme[end:]
    )
    README.write_text(updated)


if __name__ == "__main__":
    main()
